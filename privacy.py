"""
Убирает похожие на пароли/PIN/токены фрагменты текста перед тем, как он
попадёт в лог или историю. README обещает, что такое не сохраняется —
раньше это было верно только для отдельных шагов type_text с флагом
"sensitive", но НЕ для самой команды пользователя и summary целиком.
Этот модуль закрывает именно этот пробел.

Это не NLP и не идеальная защита (полноценно распознать секрет в
свободном тексте нельзя), но закрывает самый частый случай: "введи
пароль 12345" и подобные явные формулировки.
"""
import re

_PATTERNS = [
    re.compile(r"(?i)(пароль|password|пасс)\s*[:=]?\s*\S+"),
    re.compile(r"(?i)(pin|пин-?код|пин)\s*[:=]?\s*\S+"),
    re.compile(r"(?i)(код доступа|access code|passcode)\s*[:=]?\s*\S+"),
    re.compile(r"(?i)(токен|token|api[_ -]?key|ключ)\s*[:=]?\s*\S+"),
]


def redact(text: str) -> str:
    """
    Возвращает текст с похожими на секреты фрагментами, заменёнными на
    '<скрыто>'. Используется ТОЛЬКО для того, что попадает в лог/историю —
    для реального выполнения (отправки в ИИ, ввода текста) всегда
    используется исходный, нередактированный текст.
    """
    if not text:
        return text
    redacted = text
    for pattern in _PATTERNS:
        redacted = pattern.sub(lambda m: f"{m.group(1)}: <скрыто>", redacted)
    return redacted
